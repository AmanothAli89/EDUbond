    private fun q(question: String, options: List<String>, answer: String): JSONObject {
        val obj = JSONObject()
        obj.put("question", question)
        val opts = JSONArray()
        for (o in options) opts.put(o)
        obj.put("options", opts)
        obj.put("answer", answer)
        return obj
    }
