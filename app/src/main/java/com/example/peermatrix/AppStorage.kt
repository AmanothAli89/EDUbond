    fun getQuizSets(context: Context, subject: String): List<JSONArray> {
        val key = "quiz_sets_$subject"
        val data = prefs(context).getString(key, null)
        
        if (data == null) {
            val defaultSets = getDefaultSetsForSubject(subject)
            if (defaultSets != null) {
                saveQuizSets(context, subject, defaultSets)
                return getQuizSets(context, subject)
            }
        }
        
        if (data == null) return emptyList()
        val sets = JSONArray(data)
        val list = mutableListOf<JSONArray>()
        for (i in 0 until sets.length()) {
            list.add(sets.getJSONArray(i))
        }
        return list
    }

