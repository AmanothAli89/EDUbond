    private fun prefs(context: Context) =
        context.getSharedPreferences("PeerMatrixLocalDB", Context.MODE_PRIVATE)

    fun setCurrentUser(context: Context, email: String) {
        prefs(context).edit().putString("current_user", email.trim()).apply()
    }

    fun getCurrentUser(context: Context): String {
        return prefs(context).getString("current_user", "") ?: ""
    }

    fun logout(context: Context) {
        prefs(context).edit().remove("current_user").apply()
    }

